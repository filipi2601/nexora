<?php

namespace Database\Factories;

use App\Models\Material;
use App\Models\Subject;
use App\Models\User;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * @extends Factory<Material>
 */
class MaterialFactory extends Factory
{
    /**
     * Define the model's default state.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        return [
            'user_id' => User::factory(),
            'subject_id' => Subject::factory(),
            'title' => fake()->sentence(3),
            'original_name' => 'aula.pdf',
            'storage_path' => 'materials/'.fake()->uuid().'.pdf',
            'mime_type' => 'application/pdf',
            'extracted_text' => null,
            'ai_summary' => null,
            'status' => 'pending',
            'uploaded_at' => now(),
        ];
    }

    /**
     * Indicate that the material already has a summary generated by the AI.
     */
    public function summarized(): static
    {
        return $this->state(fn (array $attributes) => [
            'extracted_text' => fake()->paragraphs(3, true),
            'ai_summary' => fake()->paragraph(),
            'status' => 'ready',
        ]);
    }

    /**
     * Indicate that processing the material failed.
     */
    public function failed(): static
    {
        return $this->state(fn (array $attributes) => [
            'status' => 'failed',
        ]);
    }
}
